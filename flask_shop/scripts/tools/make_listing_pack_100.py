def _fix(products):
    """把误写成类别字符串的库存修掉，保证 100 条完整。"""
    out = []
    defaults = {
        "数码": 90, "运动": 110, "箱包": 80, "居家": 100,
        "服饰": 80, "厨房": 90, "个护": 90, "文具": 120, "工具": 80,
    }
    for row in products:
        if len(row) == 4:
            name, price, cat, intro = row
            stock = defaults.get(cat, 100)
        else:
            name, price, stock, cat, intro = row
            if isinstance(stock, str):
                intro = cat
                cat = stock
                stock = defaults.get(cat, 100)
        out.append((name, float(price), int(stock), cat, intro))
    return out


def font(size, bold=False):
    path = FONT_BD if bold and FONT_BD.exists() else FONT
    return ImageFont.truetype(str(path), size=size, index=0)


def hue_color(i, s=0.42, v=0.86):
    import colorsys
    h = (i * 0.137) % 1.0
    r, g, b = colorsys.hsv_to_rgb(h, s, v)
    return (int(r * 255), int(g * 255), int(b * 255))


def make_image(i, name, price, cat) -> bytes:
    w = h = 800
    c1 = hue_color(i, 0.35, 0.92)
    c2 = hue_color(i + 7, 0.50, 0.62)
    img = Image.new("RGB", (w, h), c1)
    px = img.load()
    for y in range(h):
        t = y / (h - 1)
        r = int(c1[0] * (1 - t) + c2[0] * t)
        g = int(c1[1] * (1 - t) + c2[1] * t)
        b = int(c1[2] * (1 - t) + c2[2] * t)
        for x in range(w):
            px[x, y] = (r, g, b)
    draw = ImageDraw.Draw(img)
    # 卡片
    card = [70, 90, 730, 710]
    shadow = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    sd = ImageDraw.Draw(shadow)
    sd.rounded_rectangle([76, 98, 736, 718], radius=36, fill=(0, 0, 0, 60))
    shadow = shadow.filter(ImageFilter.GaussianBlur(12))
    img = Image.alpha_composite(img.convert("RGBA"), shadow).convert("RGB")
    draw = ImageDraw.Draw(img)
    draw.rounded_rectangle(card, radius=36, fill=(255, 255, 255))
    # 色块「主图区」
    draw.rounded_rectangle([110, 130, 690, 430], radius=28, fill=hue_color(i, 0.40, 0.78))
    # 圆形装饰
    draw.ellipse([300, 190, 500, 390], fill=(255, 255, 255, 255) if False else (255, 255, 255))
    draw.ellipse([320, 210, 480, 370], fill=hue_color(i, 0.55, 0.55))
    # 文字
    f_cat = font(28)
    f_name = font(40, bold=True)
    f_price = font(52, bold=True)
    f_sub = font(24)
    draw.text((130, 460), cat, font=f_cat, fill=(120, 130, 140))
    # 名称换行
    max_w = 540
    line1, line2 = name, ""
    if draw.textlength(name, font=f_name) > max_w:
        for k in range(len(name), 0, -1):
            if draw.textlength(name[:k], font=f_name) <= max_w:
                line1, line2 = name[:k], name[k:]
                break
    draw.text((130, 500), line1, font=f_name, fill=(28, 32, 40))
    if line2:
        draw.text((130, 552), line2, font=f_name, fill=(28, 32, 40))
        y_price = 610
    else:
        y_price = 568
    draw.text((130, y_price), f"¥{price:.0f}", font=f_price, fill=(200, 70, 40))
    draw.text((130, 680), "云购演示 · 成品包主图", font=f_sub, fill=(150, 155, 162))
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=86, optimize=True)
    return buf.getvalue()


def main():
    products = _fix(PRODUCTS)
    if len(products) != 100:
        raise SystemExit(f"期望 100 条，实际 {len(products)}")
    names = [p[0] for p in products]
    if len(set(names)) != 100:
        raise SystemExit("商品名有重复")

    img_dir = OUT_DIR / "images"
    if OUT_DIR.exists():
        import shutil
        shutil.rmtree(OUT_DIR)
    img_dir.mkdir(parents=True)

    items = []
    for i, (name, price, stock, cat, intro) in enumerate(products, start=1):
        fn = f"{i:03d}.jpg"
        (img_dir / fn).write_bytes(make_image(i, name, price, cat))
        items.append({
            "name": name,
            "price": price,
            "stock": stock,
            "introduce": f"【{cat}】{intro}",
            "images": [f"images/{fn}"],
        })

    manifest = {"publish": True, "products": items}
    (OUT_DIR / "products.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    (OUT_DIR / "README.txt").write_text(
        "这是 100 条示例成品包。后台「商品列表 → 上传成品包上架」选择 listing_pack_100.zip 即可。\n"
        "每条都有名称、价格、库存、简介和一张主图。\n",
        encoding="utf-8",
    )

    with zipfile.ZipFile(OUT_ZIP, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for path in OUT_DIR.rglob("*"):
            if path.is_file():
                zf.write(path, path.relative_to(OUT_DIR).as_posix())

    size = OUT_ZIP.stat().st_size
    print("products", len(items))
    print("zip", OUT_ZIP, "bytes", size)
    print("dir", OUT_DIR)


if __name__ == "__main__":
    main()
